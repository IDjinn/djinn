#!/usr/bin/env bash
# Writes djinnc/src/codegen/target/cpu_table.djinn: every x86 CPU name clang knows, with the features it has of those
# [Target] and --features understand. Run it with the clang of the LLVM version djinnc links, after moving to a new one.
#
#   tools/cpu_features.sh            rewrite the table
#   tools/cpu_features.sh --check    fail when the committed table is not what this clang gives
#
# CLANG names the compiler (default: clang). A CPU the table does not know gets the SSE2 baseline, so a stale table
# never lets code use an instruction the CPU may lack.
set -eu
root="$(cd "$(dirname "$0")/.." && pwd)"
table="$root/djinnc/src/codegen/target/cpu_table.djinn"
clang="${CLANG:-clang}"
mode="${1:-}"

command -v "$clang" > /dev/null 2>&1 || { echo "cpu_features: '$clang' not found (set CLANG)" >&2; exit 2; }
major="$("$clang" -dumpversion | cut -d. -f1 | tr -d '\r')"
linked="$(sed -n 's/.*const i32 LLVM_MAJOR = \([0-9]*\);.*/\1/p' "$table" 2> /dev/null || true)"
if [ "$mode" = "--check" ] && [ "$major" != "$linked" ]; then
    echo "cpu_features: the table is for LLVM $linked and '$clang' is LLVM $major: run tools/cpu_features.sh" >&2
    exit 1
fi

# macro:feature, in the order the lists are written.
features="__SSE2__:sse2 __SSE3__:sse3 __SSSE3__:ssse3 __SSE4_1__:sse4.1 __SSE4_2__:sse4.2 __AVX__:avx __AVX2__:avx2
__AVX512F__:avx512f __AVX512BW__:avx512bw __AVX512VL__:avx512vl __AVX512DQ__:avx512dq __AVX512VNNI__:avx512vnni
__AVX512VBMI__:avx512vbmi __AVXVNNI__:avxvnni __FMA__:fma __F16C__:f16c __POPCNT__:popcnt __LZCNT__:lzcnt __BMI__:bmi
__BMI2__:bmi2 __AES__:aes __PCLMUL__:pclmul __SHA__:sha __GFNI__:gfni __VPCLMULQDQ__:vpclmulqdq"

# clang lists the names it accepts when it is given one it does not. The 32-bit target accepts all of them.
names="$(echo | "$clang" --target=i686-linux-gnu -march=unknown-cpu -E -x c - 2>&1 | tr -d '\r' \
    | sed -n 's/.*valid target CPU values are: //p' | tr -d ' ' | tr ',' '\n' | LC_ALL=C sort)"
[ -n "$names" ] || { echo "cpu_features: '$clang' did not list its CPU names" >&2; exit 2; }

out="$(mktemp)"
rows="$(mktemp)"
trap 'rm -f "$out" "$rows"' EXIT
for name in $names; do
    macros="$(echo | "$clang" --target=i686-linux-gnu "-march=$name" -dM -E -x c - | tr -d '\r' | awk '{print $2}')"
    list=""
    for pair in $features; do
        if grep -qx "${pair%%:*}" <<< "$macros"; then
            list="$list${list:+,}+${pair#*:}"
        fi
    done
    echo "${list:--} $name" >> "$rows"
done

{
    echo "// Generated by tools/cpu_features.sh from clang (LLVM $major). Do not edit: run the script again."
    echo "namespace djinnc;"
    echo
    echo "// The features of each x86 CPU name --cpu accepts, as the LLVM that djinnc links defines them."
    echo "struct CpuTable {"
    echo "    const i32 LLVM_MAJOR = $major;"
    echo
    echo "    // A \"+sse2,+avx\" list, empty for a CPU with none of them; null for a name the table does not know."
    echo "    public static ptr<i8> features(ptr<i8> cpu) {"
    # Names with the same features share one condition, four names to a line.
    LC_ALL=C sort -s -k1,1 "$rows" | awk '
        function flush(    i, line) {
            if (count == 0) { return }
            line = "        if ("
            for (i = 1; i <= count; i++) {
                if (i > 1) { line = line ((i - 1) % 3 == 0 ? "\n            || " : " || ") }
                line = line "Strings.same(cpu, \"" held[i] "\")"
            }
            value = current == "-" ? "" : current
            print line ") {\n            return \"" value "\";\n        }"
            count = 0
        }
        { if ($1 != current) { flush(); current = $1 } held[++count] = $2 }
        END { flush() }'
    echo "        return null;"
    echo "    }"
    echo "}"
} > "$out"

if [ "$mode" = "--check" ]; then
    if ! diff <(tr -d '\r' < "$table") "$out"; then
        echo "cpu_features: $table is out of date: run tools/cpu_features.sh" >&2
        exit 1
    fi
    echo "cpu_features: the table is up to date (LLVM $major)"
else
    cp "$out" "$table"
    echo "cpu_features: wrote $table ($(wc -l < "$rows" | tr -d ' ') CPUs, LLVM $major)"
fi
